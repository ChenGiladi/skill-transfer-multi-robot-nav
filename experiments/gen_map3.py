#!/usr/bin/env python3
"""
Map3 -- a third 50x50 evaluation environment for Revision 1 (Reviewer B, comment 4):
a warehouse-style corridor layout with shelf bands and staggered bottleneck doors,
structurally different from Map1/Map2's block obstacles (long aisles, narrow doors,
one vertical divider). Obstacle density ~0.26, matching Map1 (0.259) / Map2 (0.248).

Outputs (all deterministic):
  maps/map3.txt                 physical 0/1 occupancy matrix (tab-separated, map1 format)
  maps/map3_black_ranges.json   config-space mask as per-row exclusive x-intervals,
                                derived from 1-cell binary dilation of the physical map
                                (the same inflation Update1 applies), so matrix and
                                ranges are exactly consistent
  data/map3_data.csv            route library generated by the SAME offline RRT expert
                                protocol as the existing libraries: random valid
                                start/goal pairs, Apply_RRT on the inflated map
                                (RRT_MAX_ITER=8000), routes stored in the
                                alternative_data.csv format ((1,1) separator rows)

Usage: python3 gen_map3.py [--routes 3600] [--seed 777]
"""
import os, sys, json, argparse, random

import numpy as np
from scipy.ndimage import binary_dilation

_HERE = os.path.dirname(os.path.abspath(__file__))
_CODE = os.path.dirname(_HERE)
sys.path.insert(0, os.path.join(_CODE, "src"))
os.environ.setdefault("RRT_MAX_ITER", "8000")   # offline expert budget (hybrid cap)


def build_map3_matrix():
    """Physical obstacle matrix, matrix row r corresponds to y = 49 - r."""
    occ = np.zeros((50, 50), dtype=int)   # occ[y, x] in y-up coordinates

    occ[0:2, :] = 1; occ[48:50, :] = 1    # border walls, thickness 2 (as map1)
    occ[:, 0:2] = 1; occ[:, 48:50] = 1

    # Three horizontal shelf bands with staggered 5-cell doors (3 free cells after
    # 1-cell inflation), plus one vertical divider -> corridors and bottlenecks.
    occ[13:15, 2:20] = 1; occ[13:15, 25:48] = 1          # band 1, door x=20..24
    occ[23:25, 2:12] = 1; occ[23:25, 17:31] = 1; occ[23:25, 36:48] = 1  # band 2, doors x=12..16, 31..35
    occ[34:36, 2:26] = 1; occ[34:36, 31:48] = 1          # band 3, door x=26..30
    occ[25:34, 24:26] = 1                                 # vertical divider between bands 2-3

    mat = np.flipud(occ)                  # matrix row 0 = y 49
    return mat


def ranges_from_matrix(mat):
    """Per-row exclusive x-intervals of the 1-cell-inflated obstacle mask, in the
    black_ranges convention used by is_point_inside_black_ranges (x0 < x < x1)."""
    infl = binary_dilation(mat, structure=np.ones((3, 3))).astype(int)
    H = mat.shape[0]
    ranges = []
    for y in range(H):
        row = infl[H - y - 1]
        iv, x = [], 0
        while x < len(row):
            if row[x] == 1:
                x0 = x
                while x < len(row) and row[x] == 1:
                    x += 1
                iv.append((x0 - 1, x))    # exclusive bounds block exactly x0..x-1
            else:
                x += 1
        ranges.append(iv)
    return ranges


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--routes", type=int, default=3600)
    ap.add_argument("--seed", type=int, default=777)
    a = ap.parse_args()

    mat = build_map3_matrix()
    ranges = ranges_from_matrix(mat)

    # self-consistency check: ranges reproduce the inflated matrix exactly
    import Functions_code as F
    infl = binary_dilation(mat, structure=np.ones((3, 3))).astype(int)
    for y in range(50):
        for x in range(50):
            assert F.is_point_inside_black_ranges(x, y, ranges) == bool(infl[49 - y, x]), (x, y)

    np.savetxt(os.path.join(_CODE, "maps", "map3.txt"), mat, fmt="%d", delimiter="\t")
    with open(os.path.join(_CODE, "maps", "map3_black_ranges.json"), "w") as f:
        json.dump([[list(t) for t in row] for row in ranges], f)
    print(f"map3 written: obstacle fraction {mat.mean():.3f}")

    # ---- route library: same offline RRT expert protocol as the existing libraries ----
    random.seed(a.seed); np.random.seed(a.seed)
    _, up_inflated, up_black = F.Update1(mat.astype(float), ranges, [[0, 0]])
    out_rows, made, attempts = [], 0, 0
    while made < a.routes:
        attempts += 1
        starts, ends = F.generate_start_and_end(up_inflated, ranges, num_agents=1, min_distance=4)
        s, g = list(starts[0]), list(ends[0])
        try:
            route, _, _ = F.Apply_RRT(s, g, up_inflated, up_black)
        except Exception:          # RRT found no path within its budget
            continue
        if route and len(route) > 1:
            full = [s] + list(route) + [g]
            out_rows.append((1.0, 1.0))                   # separator
            out_rows.extend((float(p[0]), float(p[1])) for p in full)
            made += 1
            if made % 300 == 0:
                print(f"  {made}/{a.routes} routes ({attempts} attempts)", flush=True)
    with open(os.path.join(_CODE, "data", "map3_data.csv"), "w") as f:
        f.write("x,y\n")
        for x, y in out_rows:
            f.write(f"{x},{y}\n")
    print(f"library written: {made} routes ({attempts} attempts)")


if __name__ == "__main__":
    main()
